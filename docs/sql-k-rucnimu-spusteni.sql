--
-- Teď je tu PRÁZDNO: všechno, co web účet neumí (CREATE, ALTER, DROP…), je provedené. Poslední byly bloky
-- K (infravidění nestvůr a ras, migrace 0116–0117), L (skupina útoku u zbraně) a M (přepínač animací souboje,
-- migrace 0120) — uživatel 2026-11-13 na dotaz, jestli na stránce Změny databáze → „Co aplikace v databázi vidí“
-- svítí u všech čtyř řádků ✓, odpověděl „je to tam“.
--
-- Po ručním SQL ověřuj tam, ne číslem z phpMyAdminu: kontrolní SELECT v phpMyAdminu už vyšel 0, přestože sloupce
-- v databázi webu byly (phpMyAdmin se díval do jiné databáze). Stránka Změny databáze ukazuje databázi z pohledu webu.
--
-- Sem se zapisují jen příkazy, které stránka Změny databáze pod DML-only účtem neumí (CREATE, ALTER, DROP…).
-- Každý blok musí jít spustit opakovaně a v libovolném stavu DB (kontrola přes information_schema
-- + PREPARE/EXECUTE, CREATE TABLE IF NOT EXISTS, INSERT IGNORE), začínat kontrolou, ve KTERÉ databázi běží
-- (a ve špatné se celý přeskočit), a končit kontrolním SELECTem s očekávaným číslem. Vzor: bloky K–M v historii
-- tohoto souboru (git log -p docs/sql-k-rucnimu-spusteni.sql).
